def _body(intro, sections, outro=""):
    out = [f"<p>{intro}</p>"]
    for h, paras in sections:
        out.append(f"<h2>{h}</h2>")
        for p in paras:
            if isinstance(p, list):
                out.append("<ul>" + "".join(f"<li>{x}</li>" for x in p) + "</ul>")
            elif p.startswith("###"):
                out.append(f"<h3>{p[3:].strip()}</h3>")
            else:
                out.append(f"<p>{p}</p>")
    if outro:
        out.append(f"<p>{outro}</p>")
    return "".join(out)


